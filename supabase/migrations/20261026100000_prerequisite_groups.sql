BEGIN;

CREATE TABLE public.course_prerequisite_groups (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id bigint NOT NULL REFERENCES public.program_courses(id) ON DELETE CASCADE,
  legacy_relation_id bigint UNIQUE REFERENCES public.course_prerequisites(id) ON DELETE CASCADE,
  group_type text NOT NULL CHECK (group_type IN ('mandatory', 'alternative')),
  label text NOT NULL CHECK (length(trim(label)) BETWEEN 1 AND 120),
  position smallint NOT NULL DEFAULT 0 CHECK (position >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.course_prerequisite_group_members (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id bigint NOT NULL REFERENCES public.course_prerequisite_groups(id) ON DELETE CASCADE,
  prerequisite_course_id bigint NOT NULL REFERENCES public.program_courses(id) ON DELETE CASCADE,
  position smallint NOT NULL DEFAULT 0 CHECK (position >= 0),
  minimum_grade text CHECK (minimum_grade IS NULL OR minimum_grade IN ('A+','A','A-','B+','B','B-','C+','C','C-','D+','D','F')),
  UNIQUE (group_id, prerequisite_course_id)
);

WITH legacy_groups AS (
  INSERT INTO public.course_prerequisite_groups (course_id, legacy_relation_id, group_type, label, position)
  SELECT cp.course_id, cp.id, 'mandatory', 'Required prerequisite', row_number() OVER (PARTITION BY cp.course_id ORDER BY cp.prerequisite_course_id)-1
  FROM public.course_prerequisites cp
  RETURNING id, legacy_relation_id
)
INSERT INTO public.course_prerequisite_group_members (group_id, prerequisite_course_id, position)
SELECT g.id, cp.prerequisite_course_id, 0
FROM public.course_prerequisites cp
JOIN legacy_groups g ON g.legacy_relation_id=cp.id
;

CREATE INDEX course_prerequisite_groups_course_position_idx ON public.course_prerequisite_groups(course_id, position, id);
CREATE INDEX course_prerequisite_group_members_course_idx ON public.course_prerequisite_group_members(prerequisite_course_id);
ALTER TABLE public.course_prerequisite_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.course_prerequisite_group_members ENABLE ROW LEVEL SECURITY;

-- Group changes affect the public catalog cache in the same transaction.
CREATE TRIGGER catalog_revision_groups_insert AFTER INSERT ON public.course_prerequisite_groups
  REFERENCING NEW TABLE AS new_rows FOR EACH STATEMENT EXECUTE FUNCTION public.bump_catalog_revision_from_statement('new_rows');
CREATE TRIGGER catalog_revision_groups_update AFTER UPDATE ON public.course_prerequisite_groups
  REFERENCING NEW TABLE AS new_rows FOR EACH STATEMENT EXECUTE FUNCTION public.bump_catalog_revision_from_statement('new_rows');
CREATE TRIGGER catalog_revision_groups_delete AFTER DELETE ON public.course_prerequisite_groups
  REFERENCING OLD TABLE AS old_rows FOR EACH STATEMENT EXECUTE FUNCTION public.bump_catalog_revision_from_statement('old_rows');
CREATE TRIGGER catalog_revision_members_insert AFTER INSERT ON public.course_prerequisite_group_members
  REFERENCING NEW TABLE AS new_rows FOR EACH STATEMENT EXECUTE FUNCTION public.bump_catalog_revision_from_statement('new_rows');
CREATE TRIGGER catalog_revision_members_update AFTER UPDATE ON public.course_prerequisite_group_members
  REFERENCING NEW TABLE AS new_rows FOR EACH STATEMENT EXECUTE FUNCTION public.bump_catalog_revision_from_statement('new_rows');
CREATE TRIGGER catalog_revision_members_delete AFTER DELETE ON public.course_prerequisite_group_members
  REFERENCING OLD TABLE AS old_rows FOR EACH STATEMENT EXECUTE FUNCTION public.bump_catalog_revision_from_statement('old_rows');

COMMIT;
